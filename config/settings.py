def load_secret_key():
    """DJANGO_SECRET_KEY if set; the old insecure key for local DEBUG runs;
    otherwise a random key generated once and kept in DATA_DIR."""
    key = os.environ.get("DJANGO_SECRET_KEY", "").strip()
    if key:
        return key
    if DEBUG:
        return "django-insecure-)9yg(8e5k13$a$pj#yn+##cnepat!j^5$!js4@gr(w9!=%1vx6"
    key_file = DATA_DIR / ".secret_key"
    try:
        if key_file.exists():
            return key_file.read_text().strip()
        key = get_random_secret_key()
        key_file.write_text(key)
        key_file.chmod(0o600)
        return key
    except OSError as exc:
        raise ImproperlyConfigured(
            f"Set DJANGO_SECRET_KEY, or make {DATA_DIR} writable so a key can be stored there."
        ) from exc


# SECURITY WARNING: keep the secret key used in production secret!
